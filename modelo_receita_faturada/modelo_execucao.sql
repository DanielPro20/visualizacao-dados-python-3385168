WITH BASE AS (
    SELECT
           CC.COD_CHARGE_CODE                       AS COD_CHARGE_CODE,
           CC.DSC_CHARGE_CODE                       AS DSC_CHARGE_CODE,
           RFD.NUM_CONTA_CLI                        AS NUM_CONTA_CLI,
           CSP.COD_CSP                              AS COD_CSP,
