           OFE.COD_OFERTA                           AS COD_OFERTA,
           OFE.DSC_NOME_OFERTA                      AS DSC_NOME_OFERTA,
           OFD.DSC_NOME_OFERTA                      AS DSC_NOME_OFERTA_DESCONTO,
           TA.DSC_GRUPO_TIPO_APARELHO               AS DSC_GRUPO_TIPO_APARELHO,
           TA.DSC_TIPO_APARELHO                     AS DSC_TIPO_APARELHO,
           TR.DSC_TIPO_RECEITA                      AS DSC_TIPO_RECEITA,
           RFD.COD_PLATAFORMA                       AS COD_PLATAFORMA,
           RFD.COD_TIPO_ATIVIDADE                   AS COD_TIPO_ATIVIDADE,
           RFD.COD_UN_MEDIDA                        AS COD_UN_MEDIDA,
           RFD.DAT_FATURA                           AS DAT_FATURA,
           RFD.NUM_NTC                              AS NUM_NTC,
           RFD.NUM_SEQ_ASS                          AS NUM_SEQ_ASS,
           RFD.VAL_ALIQUOTA_FUNTEL                  AS VAL_ALIQUOTA_FUNTEL,
           RFD.VAL_ALIQUOTA_FUST                    AS VAL_ALIQUOTA_FUST,
           RFD.VAL_ALIQUOTA_ICMS                    AS VAL_ALIQUOTA_ICMS,
           RFD.VAL_ALIQUOTA_ISS                     AS VAL_ALIQUOTA_ISS,
           RFD.VAL_ALIQUOTA_PIS                     AS VAL_ALIQUOTA_PIS,
           RFD.VAL_BASE_COFINS                      AS VAL_BASE_COFINS,
           RFD.VAL_BASE_FUNTEL                      AS VAL_BASE_FUNTEL,
           RFD.VAL_BASE_FUST                        AS VAL_BASE_FUST,
           RFD.VAL_BASE_ICMS                        AS VAL_BASE_ICMS,
           RFD.VAL_BASE_ISS                         AS VAL_BASE_ISS,
           RFD.VAL_BASE_PIS                         AS VAL_BASE_PIS,
           RFD.VAL_TARIFADO_COFINS                  AS VAL_TARIFADO_COFINS,
           RFD.VAL_TARIFADO_FUNTEL                  AS VAL_TARIFADO_FUNTEL,
           RFD.VAL_TARIFADO_FUST                    AS VAL_TARIFADO_FUST,
           RFD.VAL_TARIFADO_ICMS                    AS VAL_TARIFADO_ICMS,
           RFD.VAL_TARIFADO_ISS                     AS VAL_TARIFADO_ISS,
           RFD.VAL_TARIFADO_PIS                     AS VAL_TARIFADO_PIS,
           RFD.VAL_TARIFADO_TOTAL                   AS VAL_TARIFADO_TOTAL,
           NVL(RFD.VAL_TARIFADO_TOTAL,0) - (NVL(RFD.VAL_TARIFADO_ICMS,0) + NVL(RFD.VAL_TARIFADO_ISS,0) + NVL(RFD.VAL_TARIFADO_COFINS,0) + NVL(RFD.VAL_TARIFADO_PIS,0)) AS VAL_RECEITA_LIQUIDA,
           CASE WHEN BOG.OFFER_GROUP = 'PCT_SVA' THEN 'S' ELSE 'N' END AS IND_VAS,
           POS.DUR_LIGACAO_DENTRO_FRANQUIA          AS DUR_LIGACAO_DENTRO_FRANQUIA,
           POS.DUR_LIGACAO_FORA_FRANQUIA            AS DUR_LIGACAO_FORA_FRANQUIA,
           POS.DUR_LIGACAO_REAL                     AS DUR_LIGACAO_REAL,
           POS.DUR_LIGACAO_TARIFADA                 AS DUR_LIGACAO_TARIFADA,
           RFD.DAT_FATURA                           AS DAT_MOVIMENTO,
           SYSDATE                                  AS DAT_CRIACAO_DW,
           SYSDATE                                  AS DAT_ATUALIZACAO_DW,
           CLI.DSC_NOME_CLIENTE                     AS DSC_NOME_CLIENTE,
           CLI.NUM_CNPJ                             AS NUM_CNPJ,
           ROW_NUMBER() OVER (PARTITION BY RFD.ROWID ORDER BY AM.DAT_REFERENCIA DESC, AM.DAT_ULT_CHAMADA DESC NULLS LAST, AM.DW_TIPO_APARELHO) AS RN_AM
      FROM DWH.BI_FP_RECEITA_FATURA_DET RFD
  -- regra 1: BI_FP_RECEITA_FATURADA_POS
  LEFT JOIN (
        SELECT COD_ASSINANTE,
               DAT_FATURAMENTO,
               DW_NUM_CONTA_CLI,
               DW_CHARGE_CODE,
               SUM(DUR_LIGACAO_DENTRO_FRANQUIA) AS DUR_LIGACAO_DENTRO_FRANQUIA,
               SUM(DUR_LIGACAO_FORA_FRANQUIA) AS DUR_LIGACAO_FORA_FRANQUIA,
               SUM(DUR_LIGACAO_REAL) AS DUR_LIGACAO_REAL,
               SUM(DUR_LIGACAO_TARIFADA) AS DUR_LIGACAO_TARIFADA
          FROM DWH.BI_FP_RECEITA_FATURADA_POS
         GROUP BY COD_ASSINANTE, DAT_FATURAMENTO, DW_NUM_CONTA_CLI, DW_CHARGE_CODE
    ) POS
        ON TO_CHAR(RFD.NUM_SEQ_ASS) = POS.COD_ASSINANTE
       AND RFD.DAT_FATURA = POS.DAT_FATURAMENTO
       AND RFD.DW_NUM_CONTA_CLI = POS.DW_NUM_CONTA_CLI
       AND RFD.DW_CHARGE_CODE = POS.DW_CHARGE_CODE
  -- regra 2: BI_DIM_CHARGE_CODE
  LEFT JOIN DWH.BI_DIM_CHARGE_CODE CC
        ON RFD.DW_CHARGE_CODE = CC.DW_CHARGE_CODE
  -- regra 11: BI_DIM_TIPO_RECEITA
  LEFT JOIN DWH.BI_DIM_TIPO_RECEITA TR
        ON CC.COD_TIPO_RECEITA = TR.COD_TIPO_RECEITA
  -- regra 3: Join separado do DW_OFERTA_DESCONTO
  LEFT JOIN DWH.BI_DIM_OFERTA_POS OFE
        ON RFD.DW_OFERTA = OFE.DW_OFERTA
  -- regra 4: Join separado do DW_OFERTA, traz somente a oferta de desconto
  LEFT JOIN DWH.BI_DIM_OFERTA_POS OFD
        ON RFD.DW_OFERTA_DESCONTO = OFD.DW_OFERTA
  -- regra 13: BL_OFFER_GROUPS
  LEFT JOIN MTAAPPC.BL_OFFER_GROUPS@TAOL1_RPT BOG
        ON OFE.COD_OFERTA = TO_CHAR(BOG.OFFER)
       AND BOG.OFFER_GROUP = 'PCT_SVA'
  -- regra 5: BI_DIM_CSP
  LEFT JOIN DWH.BI_DIM_CSP CSP
        ON RFD.DW_CSP = CSP.DW_CSP
  -- regra 6: Último aparelho utilizado: maior DAT_REFERENCIA até a fatura; havendo mais de um, fica o primeiro
  LEFT JOIN DWH.BI_FP_ASS_APARELHO_MENSAL AM
        ON RFD.NUM_NTC = AM.NUM_NTC
       AND RFD.DAT_FATURA >= AM.DAT_REFERENCIA
       AND RFD.NUM_CLIENTE = AM.NUM_CLIENTE
       AND AM.IND_ULT_APARELHO_UTILIZADO = 'S'
  -- regra 12: BI_DIM_TIPO_APARELHO
  LEFT JOIN DWH.BI_DIM_TIPO_APARELHO TA
        ON AM.DW_TIPO_APARELHO = TA.DW_TIPO_APARELHO
  -- regra 8: BI_DIM_CLIENTE
  LEFT JOIN DWH.BI_DIM_CLIENTE CLI
        ON RFD.DW_NUM_CLIENTE = CLI.DW_NUM_CLIENTE
       AND CLI.IND_CORPORATIVO = 'S'
     WHERE RFD.DAT_FATURA >= TO_DATE(:P_MES_REF, 'YYYYMM')
       AND RFD.DAT_FATURA < ADD_MONTHS(TO_DATE(:P_MES_REF, 'YYYYMM'), 1)
       AND RFD.IND_CORPORATIVO = 'S'
)
