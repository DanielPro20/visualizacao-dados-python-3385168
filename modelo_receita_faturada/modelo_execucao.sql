-- Arquivo gerado por gerar_modelo.py a partir de contrato.json e mapeamento.csv. Não edite à mão.
-- Carga da tabela fato de receita faturada corporativa a partir de BI_FP_RECEITA_FATURA_DET
-- Parâmetro: :P_MES_REF (YYYYMM)
-- Pendências do contrato:
--   - Nome da tabela destino: o documento diz apenas 'TABELA FATO'; usei DWOPR.TB_FATO_RECEITA_FATURADA.
--   - Campos VAL_ALIQUOTA_*, VAL_BASE_* e VAL_TARIFADO_* estão com 'regra de agregação a definir'; o modelo carrega o valor linha a linha, sem agregar.
--   - DW_CSP aparece como CHAR(2) na BI_DIM_CSP (item 6) e NUMBER na BI_FP_RECEITA_FATURA_DET (item 27); o modelo usa o da fatura (NUMBER).
--   - O join 5 (DW_CSP) não traz a condição; assumi igualdade.
--   - O item 64 liga BL_OFFER_GROUPS a RECEITA_FATURADA_POS.COD_OFERTA, mas a regra 13 e o item 55 ligam via BI_DIM_OFERTA_POS.COD_OFERTA; o modelo segue a regra 13.
--   - O filtro IND_CORPORATIVO = 'S' da BI_DIM_CLIENTE ficou na condição do LEFT JOIN para não descartar linhas da fatura; o filtro da extração é o da própria BI_FP_RECEITA_FATURA_DET.
--   - BL_OFFER_GROUPS fica na base TAOL1_RPT; o modelo acessa via database link TAOL1_RPT (ajuste o nome do dblink se for outro).

